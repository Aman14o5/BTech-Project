"""Explanation-evidence alignment (plan, Table 2): after an intervention, does the
explanation the model now writes refer to the CHANGED evidence and argue for the
label the model now predicts?

For a subset of examples the model regenerates its explanation on edited inputs
(run_experiment.py --explain_variants N). For every regenerated explanation:

  label_changed        the predicted label differs from the original prediction
  explanation_changed  the explanation text differs from the original explanation
  consistent           stance(new explanation) == new predicted label   (stance.py)
  cites_absent         the new explanation mentions a word that was in the original input
                       but is no longer in the edited input (the word the edit took away):
                       the explanation cites evidence that is not there any more
  mentions_new         (contradiction only) the new explanation mentions the substitute word.
                       For "swap"/"swap_shared" the substitute is new to the pair, so mentioning
                       it means the explanation reacts to the edit. For "align" the substitute was
                       copied from the other sentence, so it may have been mentioned before.
  argues_expected      (contradiction only, confident oracle) stance == the oracle's label
  aligned              consistent AND NOT cites_absent, and for contradiction also mentions_new:
                       the explanation argues for the new prediction, does not lean on evidence
                       that is gone, and (contradiction) refers to the new evidence

Words are compared after evidence.normalise (lower-case, punctuation, light stemming)
with stopwords removed, exactly as when finding the cited words.
"""
from evidence import STOPWORDS, normalise
from stance import stance

# variants whose explanations are regenerated by default (cited and matched control)
EXPLAIN_KEYS = [
    "premise:remove_cited", "premise:remove_random",
    "premise:isolate_cited", "premise:isolate_random",
    "premise:contradict_cited", "premise:contradict_random",
    "hypothesis:contradict_cited", "hypothesis:contradict_random",
]


def _content(text):
    return {w for w in (normalise(t) for t in str(text or "").split()) if w and w not in STOPWORDS}


def _words(text):
    return {w for w in (normalise(t) for t in str(text or "").split()) if w}


def family(key):
    name = key.split(":", 1)[1]
    if name.startswith("contradict"):
        return "contradiction"
    return "removal" if name.startswith("remove") else "isolation"


def features(r, key, min_conf=0.9):
    """Alignment features of the regenerated explanation for variant `key` of record `r`, or None."""
    ve = (r.get("variant_expl") or {}).get(key)
    if ve is None:
        return None
    v = r["variant_inputs"][key]
    y = r["original"]["label"]
    new_label = (r["variants"].get(key) or ve)["label"]
    expl = ve.get("explanation", "")
    expl_words = _content(expl)
    absent = (_content(r["premise"]) | _content(r["hypothesis"])) - (_words(v["premise"]) | _words(v["hypothesis"]))
    st = stance(expl)
    f = {
        "family": family(key),
        "new_label": new_label,
        "explanation": expl,
        "stance": st,
        "label_changed": new_label != y,
        "explanation_changed": " ".join(expl.lower().split()) != " ".join(r["original"]["explanation"].lower().split()),
        "consistent": st == new_label,
        "cites_absent": bool(absent & expl_words),
        "absent_words_cited": sorted(absent & expl_words),
    }
    if f["family"] == "contradiction":
        e = r["contradiction_edits"][key]
        f["op"] = e["op"]
        f["mentions_new"] = bool(_content(e["substitute"]) & expl_words)
        f["aligned"] = f["mentions_new"] and f["consistent"] and not f["cites_absent"]
        o = (r.get("oracle") or {}).get(key)
        if o is not None and o["probs"][o["label"]] >= min_conf:
            f["oracle_label"] = o["label"]
            f["should_change"] = o["label"] != y
            f["argues_expected"] = st == o["label"]
    else:
        f["aligned"] = f["consistent"] and not f["cites_absent"]
    return f
